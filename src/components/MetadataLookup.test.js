import { afterEach, expect, it, vi } from 'vitest'
import { mount, flushPromises, enableAutoUnmount } from '@vue/test-utils'
import MetadataLookup from './MetadataLookup.vue'
enableAutoUnmount(afterEach)
afterEach(() => vi.unstubAllGlobals())
const response = data => ({ ok: true, json: async () => data })
async function compare(edition, language = '', onStage = vi.fn()) {
  const fetch = vi.fn().mockResolvedValueOnce(response({ results: [{ editionId: 'OL1M', title: 'Example' }] })).mockResolvedValueOnce(response({ ...edition, lookup: { jobId: 'a'.repeat(32), reviewVersion: 1 } }))
  vi.stubGlobal('fetch', fetch)
  const wrapper = mount(MetadataLookup, { attachTo: document.body, props: { onStage, item: { id: 1, title: 'Example' }, draft: { language, identifiers: [] }, baseUrl: '/apps/library', requestToken: 'fixture-token' } })
  wrapper.get('details').element.open = true
  expect(fetch).not.toHaveBeenCalled()
  await wrapper.get('form').trigger('submit'); await flushPromises()
  await wrapper.get('.library-metadata-lookup-results button').trigger('click'); await flushPromises()
  return wrapper
}
it('shows raw language evidence and normalized comparison, staging only after approval', async () => {
  const staged = vi.fn()
  const wrapper = await compare({ editionId: 'OL1M', url: 'https://openlibrary.org/books/OL1M', fields: { language: 'de; en' }, languages: ['ger', 'eng'] }, 'fr; en', staged)
  expect(wrapper.text()).toContain('ger, eng')
  expect(wrapper.get('.library-metadata-lookup-field').text()).toContain('fr; en')
  expect(wrapper.get('.library-metadata-lookup-field').text()).toContain('de; en')
  expect(wrapper.text()).toContain('The suggested language differs from this book')
  expect(staged).not.toHaveBeenCalled()
  await wrapper.get('input[type=checkbox]').setValue(true)
  await wrapper.findAll('button').find(button => button.text() === 'Stage selected details').trigger('click')
  expect(staged).toHaveBeenCalledExactlyOnceWith({ language: 'de; en' }, { jobId: 'a'.repeat(32), reviewVersion: 1, fields: ['language'] })
})
it('retains unsupported language evidence without offering an editable field', async () => {
  const staged = vi.fn()
  const wrapper = await compare({ editionId: 'OL1M', fields: {}, languages: ['3ng'] }, '', staged)
  expect(wrapper.text()).toContain('3ng')
  expect(wrapper.text()).toContain('Unrecognized language evidence')
  expect(wrapper.find('input[type=checkbox]').exists()).toBe(false)
  expect(staged).not.toHaveBeenCalled()
})
it('does not warn about a different language when only the order changes', async () => {
  const wrapper = await compare({ editionId: 'OL1M', fields: { language: 'de; en' }, languages: ['ger', 'eng'] }, 'en; de')
  expect(wrapper.text()).not.toContain('The suggested language differs from this book')
})
it('searches DNB only on request and stages DNB proposals with their approval', async () => {
  const staged = vi.fn()
  const fetch = vi.fn()
    .mockResolvedValueOnce(response({ results: [{ provider: 'DNB', editionId: '123456789X', title: 'Fixture book', url: 'https://d-nb.info/123456789X' }] }))
    .mockResolvedValueOnce(response({ provider: 'DNB', editionId: '123456789X', url: 'https://d-nb.info/123456789X', fields: { publisher: 'Fixture Verlag' }, lookup: { jobId: 'd'.repeat(32), reviewVersion: 1 } }))
  vi.stubGlobal('fetch', fetch)
  const wrapper = mount(MetadataLookup, { props: { onStage: staged, item: { id: 1, title: 'Fixture book' }, draft: { publisher: '', identifiers: [] }, baseUrl: '/apps/library', requestToken: 'fixture-token' } })
  expect(wrapper.findAll('select')[1].findAll('option').map(option => option.attributes('value'))).toEqual(['isbn', 'title'])
  await wrapper.get('select').setValue('dnb')
  expect(fetch).not.toHaveBeenCalled()
  expect(wrapper.text()).toContain('Search DNB (German National Library)')
  expect(wrapper.text()).not.toContain('Other editions requests')
  await wrapper.get('form').trigger('submit'); await flushPromises()
  expect(fetch.mock.calls[0][1].body.get('provider')).toBe('dnb')
  await wrapper.get('.library-metadata-lookup-results button').trigger('click'); await flushPromises()
  expect(fetch.mock.calls[1][1].body.get('editionId')).toBe('123456789X')
  expect(staged).not.toHaveBeenCalled()
  expect(wrapper.find('.library-lookup-cover').exists()).toBe(false)
  await wrapper.get('input[type=checkbox]').setValue(true)
  await wrapper.findAll('button').find(button => button.text() === 'Stage selected details').trigger('click')
  expect(staged).toHaveBeenCalledExactlyOnceWith({ publisher: 'Fixture Verlag' }, { jobId: 'd'.repeat(32), reviewVersion: 1, fields: ['publisher'] })
})
