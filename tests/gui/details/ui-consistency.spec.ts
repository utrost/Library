import { expect, test, type Page, type TestInfo } from '@playwright/test'
import { login, openLibrary, attachCheckpoint, requiredEnvironment, collectBrowserFailures, assertKnownNextcloudLoginFailuresAndClear } from '../fixtures/nextcloud'

async function catalogueJourney(page: Page, info: TestInfo) {
  const failures = collectBrowserFailures(page)
  await login(page)
  assertKnownNextcloudLoginFailuresAndClear(failures)
  await openLibrary(page)
  const search = page.locator('.library-catalogue-search')
  await expect(search).toBeVisible()
  expect(await search.locator('input[type=search]').evaluate(el => el.getBoundingClientRect().right <= innerWidth)).toBe(true)
  await search.getByRole('searchbox').fill(requiredEnvironment('PW_SEARCH_TITLE'))
  await search.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page).toHaveURL(/q=/)
  await expect(page.locator('#library-catalogue')).toHaveAttribute('aria-busy', 'false')
  const filtered = page.url()
  const card = page.locator('.library-cover-card').first()
  await expect(card.locator('.library-cover-link')).toHaveAttribute('href', /details=/)
  await card.locator('.library-cover-link').click()
  await expect(page.locator('.library-full-details')).toBeVisible()
  await page.locator('.library-full-details-back').click()
  await expect(page).toHaveURL(filtered)
  await card.locator('.library-quick-view').click()
  await expect(page.locator('#app-sidebar-vue')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#app-sidebar-vue')).toBeHidden()
  await attachCheckpoint(page, info, 'consistent-catalogue-search-and-links')
  await page.goto('/apps/library/?home=1')
  const covers = page.locator('.library-home-row .library-cover-image')
  await expect(covers.first()).toBeVisible()
  await expect.poll(() => covers.first().evaluate(el => getComputedStyle(el).opacity)).toBe('1')
  await attachCheckpoint(page, info, 'home-visible-covers')
  failures.assertNone()
}
test('consistent search, cover links and Home covers @ux @smoke', async ({ page }, info) => catalogueJourney(page, info))
test('consistent catalogue controls on mobile @ux @mobile', async ({ page }, info) => catalogueJourney(page, info))

test('reading-list drafts survive cancelled navigation and discard explicitly @ux @smoke', async ({ page }, info) => {
  await login(page)
  await page.goto('/apps/library/?lists=1')
  const panel = page.locator('.library-personal-lists')
  await panel.getByRole('button', { name: 'New list', exact: true }).click()
  const name = panel.getByRole('textbox', { name: 'List name', exact: true })
  await name.fill('Unsaved UI review draft')
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('link', { name: 'All publications', exact: true }).first().click()
  await expect(name).toHaveValue('Unsaved UI review draft')
  await panel.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(name).toHaveCount(0)
  await attachCheckpoint(page, info, 'list-draft-discarded')
})

test('invalid import retains input in the shared shell without applying @ux @import', async ({ page }, info) => {
  await login(page)
  await page.goto('/settings/user/library')
  const portability = page.locator('.library-settings-section-portability')
  await portability.locator('summary').click()
  await portability.locator('textarea[name=metadataJson]').fill('{ invalid input')
  await portability.getByRole('button', { name: 'Preview metadata import' }).click()
  await expect(page.locator('.library-maintenance-shell')).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('not valid JSON')
  await expect(page.locator('textarea[name=metadataJson]')).toHaveValue('{ invalid input')
  await expect(page.getByRole('button', { name: 'Apply this reviewed import' })).toHaveCount(0)
  await expect(page.locator('.library-maintenance-main h1')).toHaveCSS('font-size', '24px')
  await attachCheckpoint(page, info, 'import-error-recovery')
})

test('maintenance entry points render HTML and return to the catalogue @ux @navigation', async ({ page }, info) => {
  await login(page)
  for (const path of ['languages', 'value-mappings']) {
    const response = await page.goto(`/apps/library/${path}`)
    expect(response?.ok()).toBe(true)
    await expect(page.locator('.library-maintenance-shell')).toBeVisible()
    const nav = page.locator('.library-maintenance-navigation-desktop')
    await expect(nav.getByRole('link', { name: 'Favorites', exact: true })).toBeVisible()
    await attachCheckpoint(page, info, `maintenance-${path}`)
    await nav.getByRole('link', { name: 'All publications', exact: true }).click()
    await expect(page.locator('#library-catalogue')).toBeVisible()
  }
})

test('failed author lookup offers Retry without claiming no matches @ux @details', async ({ page }) => {
  await login(page)
  const itemId = Number(requiredEnvironment('PW_ITEM_ID'))
  await page.goto(`/apps/library/?details=${itemId}`)
  await expect(page.locator('.library-identity-panel')).toBeVisible()
  let attempts = 0
  await page.route('**/apps/library/api/authors?*', async route => {
    if (route.request().method() !== 'GET') return route.continue()
    attempts++
    await route.fulfill({ status: attempts === 1 ? 503 : 200, contentType: 'application/json', body: JSON.stringify(attempts === 1 ? { error: 'temporary' } : { authors: [], hasNext: false }) })
  })
  await page.getByRole('button', { name: 'Add author', exact: true }).click()
  const picker = page.locator('.library-full-details-author-picker').first()
  await picker.getByRole('combobox').fill('Novel author')
  await expect(picker.getByRole('alert')).toBeVisible()
  await expect(picker.getByText('No matching author. You can create a separate author below.')).toHaveCount(0)
  await expect(picker.getByRole('button', { name: 'Create and add author' })).toHaveCount(0)
  await picker.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(picker.getByRole('alert')).toHaveCount(0)
  await expect(picker.getByRole('button', { name: 'Create and add author' })).toBeVisible()
  await picker.getByRole('button', { name: 'Cancel', exact: true }).click()
})
