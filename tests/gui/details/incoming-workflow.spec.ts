import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { login, collectBrowserFailures, assertKnownNextcloudLoginFailuresAndClear, attachCheckpoint, requiredEnvironment } from '../fixtures/nextcloud'
function fixture(mode = 'reset') {
  const container = requiredEnvironment('LIBRARY_LISTS_CONTAINER')
  expect(execFileSync('docker', ['inspect', '--format', '{{index .Config.Labels "library.disposable"}}', container], { encoding: 'utf8' }).trim()).toBe('personal-lists')
  const output = execFileSync('docker', ['exec', '-u', 'www-data', '-e', 'LIBRARY_DISPOSABLE_FIXTURE=1', container, 'php', '/tmp/incoming-fixture.php', mode], { encoding: 'utf8', timeout: 60000 })
  return mode === 'worker' ? null : JSON.parse(output)
}
for (const suffix of ['', ' @mobile']) test('incoming retains context through reload, details, lookup and path extraction' + suffix, async ({ page }, info) => {
  const seed = fixture()
  const failures = collectBrowserFailures(page)
  await login(page); assertKnownNextcloudLoginFailuresAndClear(failures)
  const started = Date.now()
  await page.goto(`/apps/library/?curation=1&inboxRoot=${seed.rootId}`)
  const queue = page.locator('main.curation')
  await expect(queue.locator('.inbox-row')).toHaveCount(10)
  const samples = [Date.now() - started]
  for (let sample = 0; sample < 3; sample++) {
    const began = Date.now(); await page.reload(); await expect(queue.locator('.inbox-row')).toHaveCount(10); samples.push(Date.now() - began)
  }
  await info.attach('incoming-ready-milliseconds', { body: JSON.stringify({ dataset: '60 synthetic books, newest 50 done', samples }), contentType: 'application/json' })
  await expect(queue.getByRole('combobox', { name: 'Shelf', exact: true })).toHaveValue(String(seed.rootId))
  await queue.getByRole('combobox', { name: 'Show', exact: true }).selectOption('all')
  await expect(queue.locator('.inbox-row')).toHaveCount(50)
  await queue.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(queue.locator('.inbox-row')).toHaveCount(10)
  const selected = queue.locator('.inbox-row').first()
  const title = await selected.locator('div > a').first().textContent()
  await selected.getByRole('checkbox').check()
  await page.reload()
  await expect(queue.locator('.inbox-row').first().getByRole('checkbox')).toBeChecked()
  await expect(queue.getByRole('button', { name: 'Previous', exact: true })).toBeEnabled()
  await queue.getByRole('link', { name: title!, exact: true }).click()
  await expect(page.locator('main.library-full-details')).toBeVisible()
  // Use the editor's validated return destination, not history.back's browser cache.
  const returnTo = new URL(page.url()).searchParams.get('returnTo')!
  await page.locator(`a[href="${returnTo}"]`).first().click()
  await expect(queue.locator('.inbox-row').first().getByRole('checkbox')).toBeChecked()
  await queue.getByRole('button', { name: 'Find book details', exact: true }).click()
  const lookup = page.getByRole('region', { name: 'Find book details', exact: true })
  await expect(lookup.getByRole('button', { name: 'Back to incoming books', exact: true })).toBeVisible()
  await page.reload()
  await expect(lookup).toBeVisible()
  await lookup.getByRole('button', { name: 'Back to incoming books', exact: true }).click()
  await expect(queue.locator('.inbox-row').first().getByRole('checkbox')).toBeChecked()
  await expect(queue.getByRole('combobox', { name: 'Show', exact: true })).toHaveValue('all')
  await queue.getByRole('link', { name: 'Extract metadata from this shelf', exact: true }).click()
  await expect(page.locator('section.library-inference')).toBeVisible()
  await expect(page.locator('section.library-inference .library-inference-path')).toContainText('IncomingPilot')
  await page.getByRole('link', { name: 'Back to incoming books', exact: true }).click()
  await expect(queue.locator('.inbox-row').first().getByRole('checkbox')).toBeChecked()
  await queue.getByRole('button', { name: 'Previous', exact: true }).click()
  await expect(queue.locator('.inbox-row')).toHaveCount(50)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
  await queue.getByRole('heading', { name: 'Review and organise', exact: true }).scrollIntoViewIfNeeded()
  await attachCheckpoint(page, info, 'incoming-context')
  failures.assertNone()
})
for (const suffix of ['', ' @mobile']) test('incoming organization survives reload and never pulls users back from the queue' + suffix, async ({ page }, info) => {
  test.setTimeout(90000)
  const seed = fixture()
  const failures = collectBrowserFailures(page)
  await login(page); assertKnownNextcloudLoginFailuresAndClear(failures)
  await page.goto(`/apps/library/?curation=1&inboxRoot=${seed.rootId}`)
  const queue = page.locator('main.curation')
  await expect(queue.locator('.inbox-row')).toHaveCount(10)
  await queue.locator('.inbox-row').first().getByRole('checkbox').check()
  await queue.getByRole('button', { name: 'Organise selected books', exact: true }).click()
  await queue.getByRole('combobox', { name: 'Field', exact: true }).selectOption('publisher')
  await queue.getByLabel('New value', { exact: true }).fill('Incoming workflow publisher')
  await queue.getByRole('button', { name: 'Prepare review', exact: true }).click()
  await expect(page).toHaveURL(/curationJob=[a-f0-9]{32}/)
  await page.reload()
  await expect(queue.getByRole('heading', { name: 'Publisher · Preparing review' })).toBeVisible()
  await queue.getByRole('button', { name: 'Incoming books', exact: true }).click()
  await expect(queue.locator('.inbox-row')).toHaveCount(10)
  await page.waitForTimeout(3500)
  await expect(queue.getByRole('combobox', { name: 'Show', exact: true })).toBeVisible()
  fixture('worker')
  await queue.getByRole('button', { name: 'Organisation jobs', exact: true }).click()
  await queue.locator('ul > li > button').first().click()
  await expect(queue.getByRole('button', { name: 'Apply reviewed changes', exact: true })).toBeVisible()
  await queue.getByRole('button', { name: 'Apply reviewed changes', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Apply reviewed changes', exact: true }).click()
  fixture('worker')
  await expect(queue.getByRole('heading', { name: 'Publisher · Complete' })).toBeVisible({ timeout: 15000 })
  await queue.getByRole('button', { name: 'Undo', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Undo', exact: true }).click()
  fixture('worker')
  await expect(queue.getByRole('heading', { name: 'Publisher · Undone' })).toBeVisible({ timeout: 15000 })
  await queue.getByRole('button', { name: 'Incoming books', exact: true }).click()
  const first = queue.locator('.inbox-row').first()
  await first.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(queue.getByRole('status').filter({ hasText: 'Review state saved.' })).toBeVisible()
  await page.reload()
  await expect(queue.locator('.inbox-row')).toHaveCount(9)
  await attachCheckpoint(page, info, 'incoming-organization')
  failures.assertNone()
})
