test('a pinned collection opens live catalogue filters and can be unpinned from Home', async ({ page }) => {
  fixture()
  await login(page)
  const name = 'Fixture Incoming PDFs ' + Date.now()
  await page.goto('/apps/library/?format=pdf#library-collections')
  const collections = page.locator('#library-collections')
  await collections.getByRole('textbox', { name: 'Collection name' }).fill(name)
  await collections.getByRole('button', { name: 'Save', exact: true }).click()
  await page.goto('/apps/library/?format=pdf#library-collections')
  const collection = collections.getByRole('listitem').filter({ hasText: name })
  await collection.getByRole('button', { name: 'Pin to Home' }).click()
  await expect(collection.getByRole('button', { name: 'Unpin' })).toBeVisible()
  await page.goto('/apps/library/?home=1')
  const pinned = page.locator('#library-home section').filter({ has: page.getByRole('heading', { name: 'Pinned collections' }) })
  await pinned.getByRole('link', { name }).click()
  expect(new URL(page.url()).searchParams.get('format')).toBe('pdf')
  expect(new URL(page.url()).searchParams.has('home')).toBe(false)
  await page.goBack()
  await pinned.getByRole('listitem').filter({ hasText: name }).getByRole('button', { name: 'Unpin' }).click()
  await expect(pinned.getByRole('link', { name, exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Customise Home' })).toBeVisible()
  await expect(pinned.getByRole('link', { name, exact: true })).toHaveCount(0)
})

