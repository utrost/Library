for (const suffix of ['', ' @mobile']) test('finish review saves once, guards stale decisions and advances to the queue end' + suffix, async ({ page }) => {
  const seed = fixture()
  await login(page)
  await page.goto(`/apps/library/?curation=1&inboxRoot=${seed.rootId}`)
  const rows = page.locator('.inbox-row')
  await expect(rows).toHaveCount(10)
  const nextTitle = await rows.last().locator('div > a').first().innerText()
  await rows.nth(8).locator('div > a').first().click()
  let writes = 0
  page.on('request', req => { if (req.method() === 'POST' && req.postData()?.includes('metadataAutosave')) writes++ })
  const title = page.getByRole('textbox', { name: 'Title', exact: true })
  const oldTitle = await title.inputValue()
  const revisedTitle = oldTitle + ' reviewed'
  const stale = await page.context().newPage()
  await stale.goto(page.url())
  const staleTitle = stale.getByRole('textbox', { name: 'Title', exact: true })
  await expect(staleTitle).toHaveValue(oldTitle)
  await title.fill(revisedTitle)
  await page.route('**/api/curation/inbox/*', route => route.fulfill({status: 409, contentType: 'application/json', body: '{}'}), { times: 1 })
  await page.getByRole('button', { name: 'Save, mark reviewed and next' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(title).toHaveValue(revisedTitle)
  await staleTitle.fill(oldTitle + ' stale')
  await stale.getByRole('button', { name: 'Save, mark reviewed and next' }).click()
  await expect(stale.locator('.library-full-details-error')).toContainText('changed since you opened')
  await stale.close()
  const finish = page.getByRole('button', { name: 'Mark reviewed and next', exact: true })
  await finish.click()
  await expect(title).toHaveValue(nextTitle)
  await finish.click()
  await expect(page.getByRole('status').filter({ hasText: 'end of this queue' })).toBeVisible()
  await expect(rows).toHaveCount(8)
  expect(writes).toBe(1)
})

