import { test, expect, type Page } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { login, collectBrowserFailures, assertKnownNextcloudLoginFailuresAndClear, attachCheckpoint, requiredEnvironment } from '../fixtures/nextcloud'

function worker(mode = 'worker') {
  const container = requiredEnvironment('LIBRARY_LISTS_CONTAINER')
  expect(execFileSync('docker', ['inspect', '--format', '{{index .Config.Labels "library.disposable"}}', container], { encoding: 'utf8' }).trim()).toBe('personal-lists')
  execFileSync('docker', ['exec', '-u', 'www-data', '-e', 'LIBRARY_DISPOSABLE_FIXTURE=1', container, 'php', '/tmp/curation.php', mode], { timeout: 60000 })
}
async function ready(page: Page) {
  await expect(page.locator('#library-vue-root[data-v-app]')).toBeAttached()
}
async function noOverflow(page: Page) {
  const widths = await page.evaluate(() => ({ actual: document.documentElement.scrollWidth, viewport: innerWidth }))
  expect(widths.actual).toBeLessThanOrEqual(widths.viewport + 1)
}

for (const suffix of ['', ' @mobile']) test('archive upload resumes after an acknowledged chunk loses its response' + suffix, async ({ page }, info) => {
  test.setTimeout(180000)
  worker('browser-reset')
  worker()
  const failures = collectBrowserFailures(page)
  await login(page)
  assertKnownNextcloudLoginFailuresAndClear(failures)
  await page.goto('/apps/library/?curation=1')
  await ready(page)
  const archives = page.getByRole('region', { name: 'Curation archives', exact: true })
  await archives.getByLabel('Review an archive to restore', { exact: true }).setInputFiles({ name: 'empty-curation.jsonl', mimeType: 'application/x-ndjson', buffer: Buffer.from('{"format":"library-curation","version":2,"records":0}\n') })
  await expect(archives.getByRole('status').filter({ hasText: 'This archive contains no records to restore. Nothing was changed.' })).toBeVisible()
  await archives.getByRole('button', { name: 'Delete job', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Continue', exact: true }).click()
  worker()
  await archives.getByRole('button', { name: 'Prepare curation archive', exact: true }).click()
  await expect(archives.getByRole('heading', { name: 'Preparing archive', exact: true })).toBeVisible()
  worker()
  const link = archives.getByRole('link', { name: 'Download archive', exact: true })
  await expect(link).toBeVisible({ timeout: 15000 })
  const response = await page.request.get((await link.getAttribute('href'))!)
  expect(response.ok()).toBeTruthy()
  // Keep repeated browser runs bounded. Full-account transfers are covered by the PHP harness.
  const lines = (await response.text()).trim().split('\n').map(line => JSON.parse(line))
  const manifest = lines.shift()
  const book = lines.find(record => record.kind === 'book')
  expect(book).toBeTruthy()
  const references = {
    author: new Set((book.data.links.authors || []).map(String)),
    series: new Set(book.data.links.series == null ? [] : [String(book.data.links.series)]),
    genre: new Set([...(book.data.links.genres || []), ...(book.data.suppressedGenres || [])].map(String)),
  }
  let historyCount = 0
  const records = lines.filter(record => record === book
    || references[record.kind]?.has(String(record.key))
    || (record.kind === 'history' && String(record.data.item_id) === String(book.key) && historyCount++ < 2))
  const buffer = Buffer.from([JSON.stringify({ ...manifest, records: records.length }), ...records.map(record => JSON.stringify(record)), ''].join('\n'))
  const archive = { name: 'disposable-curation.jsonl', mimeType: 'application/x-ndjson', buffer }
  await archives.getByRole('button', { name: 'Delete job', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Continue', exact: true }).click()
  worker()
  let interrupted = false
  await page.route('**/api/curation/archives/*/upload', async route => {
    if (interrupted) return route.continue()
    const accepted = await route.fetch()
    expect(accepted.ok()).toBeTruthy()
    interrupted = true
    await route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"fixture_lost_response"}' })
  })
  await archives.getByLabel('Review an archive to restore', { exact: true }).setInputFiles(archive)
  await expect(archives.getByRole('alert')).toContainText('Could not complete the operation')
  expect(interrupted).toBeTruthy()
  failures.assertNoneOrExactSetAndClear([/^console: Failed to load resource: the server responded with a status of 503 \(Service Unavailable\)$/])
  await archives.getByLabel('Resume upload with the same archive', { exact: true }).setInputFiles(archive)
  await expect(archives.getByRole('heading', { name: 'Preparing review', exact: true })).toBeVisible()
  worker()
  await expect(archives.getByRole('heading', { name: 'Ready for review', exact: true })).toBeVisible({ timeout: 15000 })
  const row = archives.getByRole('row').filter({ has: page.getByRole('button', { name: 'Skip', exact: true }) }).first()
  await row.getByRole('button', { name: 'Skip', exact: true }).click()
  const skipped = archives.getByRole('row').filter({ has: page.getByRole('button', { name: 'Include', exact: true }) }).first()
  await expect(skipped).toContainText('Skipped')
  await skipped.getByRole('button', { name: 'Include', exact: true }).click()
  await expect(archives.getByRole('button', { name: 'Include', exact: true })).toHaveCount(0)
  await noOverflow(page)
  if (info.project.name === 'mobile-chromium') expect(await archives.locator('.archive-table').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBeTruthy()
  await attachCheckpoint(page, info, 'archive-restore-review')
  await archives.getByRole('button', { name: 'Restore reviewed records', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(archives.getByRole('heading', { name: 'Ready for review', exact: true })).toBeVisible()
  await archives.getByRole('button', { name: 'Restore reviewed records', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Continue', exact: true }).click()
  worker()
  await expect(archives.getByRole('heading', { name: 'Complete', exact: true })).toBeVisible({ timeout: 15000 })
  await expect(archives.getByRole('cell', { name: /Applied/ }).first()).toBeVisible()
  await archives.getByRole('button', { name: 'Delete job', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Continue', exact: true }).click()
  failures.assertNone()
})

