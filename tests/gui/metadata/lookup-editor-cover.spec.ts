import { test, expect } from '@playwright/test'
import { login } from '../fixtures/nextcloud'
import { readFileSync } from 'node:fs'
test.skip(!process.env.PW_EDITOR_FIXTURE, 'Requires disposable lookup_editor_cover_integration fixture')
async function journey(page, testInfo) {
  const fixture = JSON.parse(readFileSync(process.env.PW_EDITOR_FIXTURE!, 'utf8'))
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  let external = 0
  await page.route(/https:\/\/(covers\.openlibrary\.org|openlibrary\.org|books\.google\.com)\//, route => { external++; return route.abort() })
  await login(page)
  const base = `/apps/library/items/${fixture.itemId}`
  await page.route(`**${base}/metadata-lookup`, route => route.fulfill({ json: { results: [{ editionId: 'OL1M', title: 'Example edition' }] } }))
  await page.route(`**${base}/metadata-lookup/edition`, route => route.fulfill({ json: fixture.edition }))
  await page.route(`**/api/metadata-batches/${fixture.job.id}/books/${fixture.itemId}/cover-preview`, route => route.fulfill({ json: fixture.job }))
  await page.goto(`/apps/library/?details=${fixture.itemId}`)
  const lookup = page.locator('.library-metadata-lookup')
  await lookup.locator('summary').click()
  await lookup.getByRole('button', { name: 'Search Open Library', exact: true }).click()
  await lookup.getByRole('button', { name: /Compare edition OL1M/ }).click()
  const beforeImage = await (await page.request.get(`${base}/cover?refresh=1`)).body()
  const before = (await (await page.request.get(`${base}/sidebar`)).json()).item
  await lookup.getByRole('button', { name: 'Preview cover from Open Library' }).click()
  const suggestion = lookup.getByRole('img', { name: 'Suggested cover', exact: true })
  await expect(suggestion).toBeVisible()
  await expect.poll(() => suggestion.evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('editor-cover-comparison.png'), fullPage: true })
  await lookup.getByRole('checkbox', { name: 'Publisher', exact: true }).check()
  await lookup.getByRole('checkbox', { name: 'Use this cover, replacing the current cover if present', exact: true }).check()
  await lookup.getByRole('button', { name: 'Stage selected details' }).click()
  expect(await (await page.request.get(`${base}/cover?refresh=1`)).body()).toEqual(beforeImage)
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  expect(await (await page.request.get(`${base}/cover?refresh=1`)).body()).toEqual(beforeImage)
  await lookup.getByRole('checkbox', { name: 'Publisher', exact: true }).check()
  await lookup.getByRole('checkbox', { name: 'Use this cover, replacing the current cover if present', exact: true }).check()
  await lookup.getByRole('button', { name: 'Stage selected details' }).click()
  await page.getByRole('button', { name: 'Save book details', exact: true }).click()
  await expect(page.getByText('Book details saved', { exact: true })).toBeVisible()
  const after = (await (await page.request.get(`${base}/sidebar`)).json()).item
  expect(after.publisher).toBe('Cover Press')
  expect(await (await page.request.get(`${base}/cover?refresh=1`)).body()).not.toEqual(beforeImage)
  const activity = page.locator('details').filter({ has: page.locator(':scope > summary', { hasText: /^Notes and change history$/ }) })
  await activity.locator(':scope > summary').click()
  const history = activity.locator('details').filter({ has: page.locator(':scope > summary', { hasText: /^Lookup change history$/ }) })
  await history.locator(':scope > summary').click()
  await expect(history.getByText('Cover replaced', { exact: true })).toBeVisible()
  await history.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(history.getByText('Undone', { exact: true })).toBeVisible()
  const undone = (await (await page.request.get(`${base}/sidebar`)).json()).item
  expect(undone.publisher).toBe(before.publisher)
  expect(await (await page.request.get(`${base}/cover?refresh=1`)).body()).toEqual(beforeImage)
  await page.screenshot({ path: testInfo.outputPath('editor-cover-receipt.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
  expect(external).toBe(0); expect(errors).toEqual([])
}
test('one-book staged provider details and cover save atomically, discard and Undo', async ({ page }, testInfo) => journey(page, testInfo))
test('one-book cover comparison and receipts on mobile @mobile', async ({ page }, testInfo) => journey(page, testInfo))

async function batchJourney(page, testInfo) {
  const fixture = JSON.parse(readFileSync(process.env.PW_EDITOR_FIXTURE!, 'utf8')); const job = fixture.batchCoverJob; const itemId = job.rows[0].id
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await login(page)
  await page.route(`**/api/metadata-batches/${job.id}/books/${itemId}/cover-preview`, route => route.fulfill({ json: job }))
  await page.goto(`/apps/library/?metadataLookup=1&lookupJob=${job.id}`)
  const row = page.locator('.library-batch-book').first()
  const before = await (await page.request.get(`/apps/library/items/${itemId}/cover?refresh=1`)).body()
  await row.getByRole('button', { name: 'Preview cover from Open Library' }).click()
  await expect(row.getByRole('img', { name: 'Suggested cover', exact: true })).toBeVisible()
  await row.getByRole('checkbox', { name: 'Use this cover, replacing the current cover if present', exact: true }).check()
  await expect(page.getByRole('region', { name: 'Find book details', exact: true })).toContainText('1 field selected')
  expect(await (await page.request.get(`/apps/library/items/${itemId}/cover?refresh=1`)).body()).toEqual(before)
  await page.evaluate(() => { document.body.removeAttribute('data-theme-light'); document.body.setAttribute('data-theme-dark', '') })
  await page.screenshot({ path: testInfo.outputPath('bulk-cover-dark.png'), fullPage: true })
  await row.getByRole('button', { name: 'Apply now', exact: true }).click()
  await expect(row.getByText('Applied', { exact: true })).toBeVisible()
  expect(await (await page.request.get(`/apps/library/items/${itemId}/cover?refresh=1`)).body()).not.toEqual(before)
  await row.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(row.getByText('Undone', { exact: true })).toBeVisible()
  expect(await (await page.request.get(`/apps/library/items/${itemId}/cover?refresh=1`)).body()).toEqual(before)
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
  expect(errors).toEqual([])
}
test('batch cover stays unchanged until approved and can be undone', async ({ page }, testInfo) => batchJourney(page, testInfo))
test('batch cover comparison wraps on mobile @mobile', async ({ page }, testInfo) => batchJourney(page, testInfo))
