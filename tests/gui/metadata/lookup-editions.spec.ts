import { test, expect, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { login, collectBrowserFailures, assertKnownNextcloudLoginFailuresAndClear, attachCheckpoint, requiredEnvironment } from '../fixtures/nextcloud'

test.skip(!process.env.PW_EDITIONS_FIXTURE, 'Requires the disposable lookup_editions_browser_fixture')
function fixture() { return JSON.parse(readFileSync(requiredEnvironment('PW_EDITIONS_FIXTURE'), 'utf8')) }
function worker() {
  const container = requiredEnvironment('LIBRARY_LISTS_CONTAINER')
  expect(execFileSync('docker', ['inspect', '--format', '{{index .Config.Labels "library.disposable"}}', container], { encoding: 'utf8' }).trim()).toBe('personal-lists')
  execFileSync('docker', ['exec', '-u', 'www-data', '-e', 'LIBRARY_DISPOSABLE_FIXTURE=1', container, 'php', '/tmp/lookup-editions.php', 'advance'], { timeout: 30000 })
}
async function overflow(page: Page) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true) }

for (const suffix of ['', ' @mobile']) test('single-book alternative edition paging stages one reviewed choice' + suffix, async ({ page }, info) => {
  test.setTimeout(90000)
  const data = fixture(), failures = collectBrowserFailures(page)
  await login(page); assertKnownNextcloudLoginFailuresAndClear(failures)
  const base = `/apps/library/items/${data.itemId}`
  await page.route(`**${base}/metadata-lookup`, route => route.fulfill({ json: { results: [data.candidate] } }))
  const offsets: number[] = []
  await page.route(`**${base}/metadata-lookup/editions`, route => {
    const offset = Number(route.request().postData()?.match(/name="offset"\r\n\r\n(\d+)/)?.[1] || 0)
    offsets.push(offset)
    return route.fulfill({ json: offset === 0 ? data.page : data.lastPage })
  })
  await page.route(`**${base}/metadata-lookup/edition`, route => route.fulfill({ json: data.edition }))
  await page.goto(`/apps/library/?details=${data.itemId}`)
  const lookup = page.locator('.library-metadata-lookup')
  await lookup.locator('summary').click()
  await lookup.getByRole('button', { name: 'Search Open Library', exact: true }).click()
  await lookup.getByRole('button', { name: 'Other editions: Original fixture edition', exact: true }).focus()
  await page.keyboard.press('Enter')
  const editions = lookup.getByRole('region', { name: 'Other editions', exact: true })
  await expect(editions.getByRole('heading')).toBeFocused()
  await expect(editions).toContainText('Alternate fixture edition')
  await expect(editions).toContainText('not a verified match')
  await expect(editions.getByRole('button', { name: 'Previous editions', exact: true })).toBeDisabled()
  await editions.getByRole('button', { name: 'Next editions', exact: true }).click()
  await expect(editions).toContainText('No usable editions on this page')
  await expect(editions.getByRole('button', { name: 'Next editions', exact: true })).toBeDisabled()
  await editions.getByRole('button', { name: 'Previous editions', exact: true }).click()
  await expect(editions).toContainText('Alternate fixture edition')
  await overflow(page); await attachCheckpoint(page, info, 'single-alternative-editions')
  await editions.getByRole('button', { name: 'Compare edition OL4M: Alternate fixture edition', exact: true }).click()
  await lookup.getByRole('checkbox', { name: 'Publisher', exact: true }).check()
  await lookup.getByRole('button', { name: 'Stage selected details', exact: true }).click()
  const read = async () => (await (await page.request.get(`${base}/sidebar`)).json()).item
  expect((await read()).publisher).toBe('')
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  expect((await read()).publisher).toBe('')
  await lookup.getByRole('checkbox', { name: 'Publisher', exact: true }).check()
  await lookup.getByRole('button', { name: 'Stage selected details', exact: true }).click()
  await page.getByRole('button', { name: 'Save book details', exact: true }).click()
  await expect(page.getByText('Book details saved', { exact: true })).toBeVisible()
  expect((await read()).publisher).toBe('Alternate Fixture Press')
  const activity = page.locator('details').filter({ has: page.locator(':scope > summary', { hasText: /^Notes and change history$/ }) })
  await activity.locator(':scope > summary').click()
  const receipts = activity.locator('details').filter({ has: page.locator(':scope > summary', { hasText: /^Lookup change history$/ }) })
  await receipts.locator(':scope > summary').click()
  await receipts.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(receipts.getByText('Undone', { exact: true })).toBeVisible()
  expect((await read()).publisher).toBe('')
  expect(offsets).toEqual([0, 8, 0]); failures.assertNone()
})

for (const suffix of ['', ' @mobile']) test('batch edition browsing clears old approvals and persists the reviewed page' + suffix, async ({ page }, info) => {
  test.setTimeout(120000)
  const data = fixture(), failures = collectBrowserFailures(page)
  await login(page); assertKnownNextcloudLoginFailuresAndClear(failures)
  await page.goto(`/apps/library/?metadataLookup=1&lookupJob=${data.jobId}`)
  const panel = page.getByRole('region', { name: 'Find book details', exact: true }), row = panel.locator('article').first()
  await expect(row.getByRole('checkbox', { name: /^Publisher Before:/ })).toBeChecked()
  await row.getByText('Edition matches', { exact: true }).click()
  await row.getByRole('button', { name: 'Other editions: Original fixture edition', exact: true }).click()
  await expect(panel).toContainText('Previous edition approvals were cleared')
  await expect(row).toContainText('Loading other editions…')
  worker()
  const editions = row.getByRole('region', { name: 'Other editions', exact: true })
  await expect(editions).toContainText('Alternate fixture edition')
  await expect(row.getByRole('checkbox')).toHaveCount(0)
  await page.reload(); await expect(editions).toContainText('Alternate fixture edition')
  await editions.getByRole('button', { name: 'Next editions', exact: true }).click()
  await expect(row).toContainText('Loading other editions…'); worker()
  await expect(editions).toContainText('No usable editions on this page')
  await expect(editions.getByRole('button', { name: 'Next editions', exact: true })).toBeDisabled()
  await editions.getByRole('button', { name: 'Previous editions', exact: true }).click()
  await expect(row).toContainText('Loading other editions…'); worker()
  await expect(editions).toContainText('Alternate fixture edition')
  await overflow(page); await attachCheckpoint(page, info, 'batch-alternative-editions')
  await editions.getByRole('button', { name: 'Review this edition OL4M: Alternate fixture edition', exact: true }).click()
  await expect(row.getByText('Queued', { exact: true })).toBeVisible(); worker()
  await expect(row.getByRole('checkbox', { name: /^Publisher Before:/ })).not.toBeChecked()
  await row.getByRole('checkbox', { name: /^Publisher Before:/ }).check()
  await row.getByRole('button', { name: 'Apply now', exact: true }).click()
  await expect(row.getByText('Applied', { exact: true })).toBeVisible()
  const read = async () => (await (await page.request.get(`/apps/library/items/${data.batchItemId}/sidebar`)).json()).item
  expect((await read()).publisher).toBe('Alternate Fixture Press')
  await row.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(row.getByText('Undone', { exact: true })).toBeVisible()
  expect((await read()).publisher).toBe(''); failures.assertNone()
})
